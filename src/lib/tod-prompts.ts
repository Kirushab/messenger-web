export type TodKind = 'truth' | 'dare';

/** Случайная подсказка нужного типа из выбранных категорий, кроме уже использованных. */
export function pickPrompt(
  activeCategoryIds: string[],
  kind: TodKind,
  used: Set<string>,
  categories: TodCategory[] = TOD_CATEGORIES,
): string | null {
  const pool = categories
    .filter(c => activeCategoryIds.includes(c.id))
    .flatMap(c => (kind === 'truth' ? c.truths : c.dares))
    .filter(p => !used.has(p));
  if (pool.length === 0) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}

/** Есть ли подсказки данного типа в выбранных категориях (без учёта использованных). */
export function hasKind(
  activeCategoryIds: string[],
  kind: TodKind,
  categories: TodCategory[] = TOD_CATEGORIES,
): boolean {
  return categories.some(c => activeCategoryIds.includes(c.id) && (kind === 'truth' ? c.truths.length > 0 : c.dares.length > 0));
}
