-- ============================================================
-- 073_messages_spoiler.sql
-- Скрытые («спойлер») сообщения — текст замазывается blur'ом
-- пока получатель не нажмёт. Состояние «открыто/закрыто» хранится
-- на клиенте (localStorage) — серверу не нужно отслеживать кто увидел.
-- ============================================================

ALTER TABLE public.messages
  ADD COLUMN IF NOT EXISTS is_spoiler boolean NOT NULL DEFAULT false;

-- Индекс не нужен — это локальный флаг для UI

COMMENT ON COLUMN public.messages.is_spoiler IS
  'Скрытое сообщение (spoiler). Клиент мажет блюром текст/медиа пока пользователь не тапнет.';
